"""Apply the duplicate rule to the searched corpus, before screening.

Groups the records of datasets/references.json that share a normalized title. The extra
records of a group are removed only when the rule of src/duplicates.py allows it; every
other group is kept whole. Nothing is deleted from the corpus file. Writes
datasets/duplicates.csv, one row per removed record with the record kept in its place, which
runners/make_tables.py counts in the flow diagram. Writes results/corpus/duplicates.md: the
counts, every removed record and every group kept whole.

Run: python runners/run_all.py --only deduplicate
"""

import argparse
import csv
import os
import sys
import tomllib
from collections import Counter

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from src import corpus  # noqa: E402
from src.duplicates import KINDS, decide  # noqa: E402

FIELDS = ["number", "duplicate_of", "kind", "title", "doi", "kept_doi", "first_author",
          "work_type", "year"]


def rows(removed):
    return [{"number": r.number, "duplicate_of": keep.number, "kind": kind,
             "title": r.title, "doi": r.doi, "kept_doi": keep.doi,
             "first_author": r.first_author, "work_type": r.work_type, "year": r.year or ""}
            for r, keep, kind in sorted(removed, key=lambda x: x[0].number)]


def render(n, removed, kept_groups, removable):
    by_kind = Counter(kind for _, _, kind in removed)
    out = ["# Duplicates removed before screening", "",
           "Generated by `runners/deduplicate.py` from `configs/deduplicate.toml`. "
           "Do not edit; regenerate.", "",
           "Rule: the extra records of a group sharing a normalised title are removed when "
           "the group's kind is one of %s and its first authors agree. Every other group is "
           "kept whole." % ", ".join("`%s`" % k for k in removable), "",
           "| Measure | Count |", "|---|---|",
           "| Records in the corpus | %d |" % n,
           "| Duplicates removed | %d |" % len(removed),
           "| Records to screen | %d |" % (n - len(removed))]
    out += ["| &nbsp;&nbsp; removed as `%s` | %d |" % (k, by_kind.get(k, 0))
            for k, _ in KINDS if k in removable]
    out += ["| Groups kept whole | %d |" % len(kept_groups), ""]
    out += ["## Removed, with the record kept in its place", "",
            "| Removed | Kept | Kind | Title | Removed DOI | Kept DOI |", "|---|---|---|---|---|---|"]
    for row in rows(removed):
        out.append("| %s | %s | %s | %s | %s | %s |" % (
            row["number"], row["duplicate_of"], row["kind"],
            (row["title"] or "").replace("|", "/"), row["doi"] or "(none)",
            row["kept_doi"] or "(none)"))
    out += ["", "## Kept whole", "",
            "Screened as separate records. Where more than one record of a group is included, "
            "they are assessed at full text as possible versions of one study.", "",
            "| Records | Kind | First authors agree | Title | Numbers |", "|---|---|---|---|---|"]
    for group, kind, agree in kept_groups:
        out.append("| %d | %s | %s | %s | %s |" % (
            len(group), kind, agree, (group[0].title or "").replace("|", "/"),
            ", ".join(str(r.number) for r in group)))
    return "\n".join(out) + "\n"


def resolve(path):
    return os.path.normpath(os.path.join(REPO, path))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=os.path.join(REPO, "configs", "deduplicate.toml"))
    args = parser.parse_args()
    with open(args.config, "rb") as fh:
        cfg = tomllib.load(fh)

    records = corpus.load_references(resolve(cfg["inputs"]["corpus"]))
    rule = cfg["rule"]
    removable = rule["removable_kinds"]
    unknown = [k for k in removable if k not in dict(KINDS)]
    if unknown:
        raise SystemExit("unknown kind(s) in removable_kinds: %s" % ", ".join(unknown))
    removed, kept_groups = decide(records, rule.get("repository_doi_prefixes", []), removable)

    removed_path = resolve(cfg["outputs"]["removed"])
    with open(removed_path, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows(removed))
    report_path = resolve(cfg["outputs"]["report"])
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(len(records), removed, kept_groups, removable))

    by_kind = Counter(kind for _, _, kind in removed)
    print("records           : %d" % len(records))
    print("duplicates removed: %d (%s)" % (len(removed), ", ".join(
        "%s %d" % (k, by_kind.get(k, 0)) for k in removable)))
    print("records to screen : %d" % (len(records) - len(removed)))
    print("groups kept whole : %d" % len(kept_groups))
    print("wrote %s and %s" % (os.path.relpath(removed_path, REPO), os.path.relpath(report_path, REPO)))


if __name__ == "__main__":
    main()
